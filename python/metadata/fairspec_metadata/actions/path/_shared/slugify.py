from __future__ import annotations

import re
import unicodedata

COMBINING_MARKS = re.compile("[̀-ͯ︠-︯⃐-⃿]")
DEBURRABLE_LETTERS = re.compile("[À-ÖØ-öø-ÿĀ-ſ]")


def slugify_text(text: str, *, separator: str = "-") -> str:
    for key, value in REPLACEMENTS:
        text = text.replace(key, value)

    text = DEBURRABLE_LETTERS.sub(
        lambda match: DEBURRED_LETTERS.get(match[0], match[0]), text
    )
    text = COMBINING_MARKS.sub("", text)
    text = unicodedata.normalize("NFKD", text)

    text = re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", text)
    text = re.sub(r"([A-Z]+)([A-Z][a-z0-9]+)", r"\1 \2", text)

    text = re.sub(r"[^a-z0-9]+", separator, text.lower())
    text = re.sub(f"{re.escape(separator)}{{2,}}", separator, text)
    return text.strip(separator)


