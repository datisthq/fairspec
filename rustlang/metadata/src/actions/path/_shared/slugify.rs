use std::sync::LazyLock;

use regex::Regex;
use unicode_normalization::UnicodeNormalization;

static CAMEL_CASE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"([a-z0-9])([A-Z])").unwrap());
static CAPITALS: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"([A-Z]+)([A-Z][a-z0-9]+)").unwrap());
static NON_ALPHANUMERIC: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"[^a-z0-9]+").unwrap());

pub fn slugify_text(text: &str, separator: &str) -> String {
    let mut text = text.to_string();
    for (key, value) in REPLACEMENTS {
        text = text.replace(key, value);
    }

    let mut deburred = String::with_capacity(text.len());
    for char in text.chars() {
        match get_deburred_letter(char) {
            Some(letter) => deburred.push_str(letter),
            None => deburred.push(char),
        }
    }
    let text: String = deburred
        .chars()
        .filter(|char| !get_is_combining_mark(*char))
        .collect();
    let text: String = text.nfkd().collect();

    let text = CAMEL_CASE.replace_all(&text, "${1} ${2}");
    let text = CAPITALS.replace_all(&text, "${1} ${2}");

    let text = NON_ALPHANUMERIC
        .replace_all(&text.to_lowercase(), separator)
        .into_owned();
    let repeated = Regex::new(&format!("(?:{}){{2,}}", regex::escape(separator))).unwrap();
    let text = repeated.replace_all(&text, separator);
    text.trim_matches(|char| separator.contains(char))
        .to_string()
}

fn get_is_combining_mark(char: char) -> bool {
    matches!(char, '\u{300}'..='\u{36f}' | '\u{fe20}'..='\u{fe2f}' | '\u{20d0}'..='\u{20ff}')
}

fn get_deburred_letter(char: char) -> Option<&'static str> {
    let is_deburrable = matches!(char, '\u{c0}'..='\u{d6}' | '\u{d8}'..='\u{f6}' | '\u{f8}'..='\u{ff}' | '\u{100}'..='\u{17f}');
    if !is_deburrable {
        return None;
    }
    let mut buffer = [0; 4];
    let letter: &str = char.encode_utf8(&mut buffer);
    DEBURRED_LETTERS
        .iter()
        .find(|(key, _)| *key == letter)
        .map(|(_, deburred)| *deburred)
}

